PLURAL = 'nplurals=3; plural=(n%10==1 && n%100!=11 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);'

def q(s):
	return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'

def main(root):
	msgs = extract(root)
	# po2lmo/LuCI do not find a message whose msgid starts or ends with a space: write _('Name:') + ' '
	edged = [ m['id'] for m in msgs if m['id'] != m['id'].strip() and m['id'].strip() ]
	if edged:
		sys.exit('messages with a leading/trailing space (they would stay untranslated):\n  ' + '\n  '.join(repr(x) for x in edged))
	missing = []
	out = ['msgid ""', 'msgstr ""', q('Content-Type: text/plain; charset=UTF-8\n'), q('Language: ru\n'), q('Plural-Forms: ' + PLURAL + '\n'), '']
	for m in msgs:
		if m['plural']:
			t = RU.get((m['id'], m['plural']))
			if not t: missing.append(m['id']); continue
			out += [ 'msgid ' + q(m['id']), 'msgid_plural ' + q(m['plural']) ] + [ 'msgstr[%d] %s' % (i, q(x)) for i, x in enumerate(t) ] + [ '' ]
		else:
			t = RU.get(m['id'])
			if t is None: missing.append(m['id']); continue
			out += [ 'msgid ' + q(m['id']), 'msgstr ' + q(t), '' ]
	if missing:
		sys.exit('untranslated:\n  ' + '\n  '.join(missing))
	d = os.path.join(root, 'po', 'ru'); os.makedirs(d, exist_ok=True)
	open(os.path.join(d, 'detour.po'), 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
	print('%d messages -> %s' % (len(msgs), os.path.join(d, 'detour.po')))

if __name__ == '__main__':
	main(sys.argv[1])
